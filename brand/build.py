#!/usr/bin/env python3
"""Generate every themed surface from brand/tokens.toml.

Static outputs (checked in): the uikit token object, the always-dark Konsole scheme,
the Plasma colour schemes and the light/dark look-and-feel packages. Outputs that depend
on the screen size are built at install time by brand/splash.py and brand/wallpaper.py.

    python3 brand/build.py           # write generated files
    python3 brand/build.py --check   # exit 1 if generated files are stale
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "GENERATED by brand/build.py from brand/tokens.toml. Do not edit."


def resolve(t: dict) -> dict:
    """Terminal colours may name another colour token ("accent", "dark.bg"); resolve them."""
    c = t["color"]
    for k, v in c["terminal"].items():
        if not v.startswith("#"):
            node = c
            for part in v.split("."):
                node = node[part]
            c["terminal"][k] = node
    return t


def load() -> dict:
    with open(ROOT / "brand" / "tokens.toml", "rb") as f:
        return resolve(tomllib.load(f))


def qml_tokens(t: dict) -> str:
    c = t["color"]
    light, dark = c["light"], c["dark"]
    lines = [
        f"// {HEADER}",
        "import QtQuick",
        "",
        "QtObject {",
        "    property bool dark: false",
        "",
        f"    readonly property real frameWidth: {t['frame']['width']}",
        f"    readonly property real frameHeight: {t['frame']['height']}",
        f"    readonly property int gridColumns: {t['grid']['columns']}",
        f"    readonly property real gridMargin: {t['grid']['margin']}",
        f"    readonly property real gridGutter: {t['grid']['gutter']}",
        f"    readonly property real displayWidth: {t['display']['width']}",
        f"    readonly property real displayHeight: {t['display']['height']}",
        f"    readonly property real displayMargin: {t['display']['margin']}",
        f"    readonly property real displayGutter: {t['display']['gutter']}",
        *[f"    readonly property real shell{k.title().replace('_', '')}: {v}" for k, v in t["shell"].items()],
        "",
    ]
    for k in ("accent", "success", "warning", "error", "on_status"):
        lines.append(f'    readonly property color {k.replace("_s", "S")}: "{c[k]}"')
    lines.append(f'    readonly property color bootBg: "{t["boot"]["bg"]}"     // boot splash, lock screen')
    for k in light:
        lines.append(f'    readonly property color {k}: dark ? "{dark[k]}" : "{light[k]}"')
    lines.append("")
    for k, v in t["font"].items():
        lines.append(f'    readonly property string font{k.capitalize()}: "{v}"')
    lines.append("")
    for name, s in t["type"].items():
        fam = t["font"][s["family"]]
        lines.append(
            f"    readonly property var {name}: ({{ family: \"{fam}\", size: {s['size']}, "
            f"weight: {s['weight']}, width: {s.get('width', 100)}, "
            f"tracking: {s.get('tracking', 0)}, upper: {str(s.get('upper', False)).lower()} }})"
        )
    lines.append("")
    for k, v in t["radius"].items():
        lines.append(f"    readonly property real radius{k.capitalize()}: {v}")
    for k, v in t["motion"].items():
        lines.append(f"    readonly property int motion{k.capitalize()}: {v}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def rgb(h: str) -> str:
    h = h.lstrip("#")
    return ",".join(str(int(h[i : i + 2], 16)) for i in (0, 2, 4))


def mix(a: str, b: str, f: float) -> str:
    pa = [int(a.lstrip("#")[i : i + 2], 16) for i in (0, 2, 4)]
    pb = [int(b.lstrip("#")[i : i + 2], 16) for i in (0, 2, 4)]
    return "#" + "".join(f"{round(x + (y - x) * f):02X}" for x, y in zip(pa, pb, strict=True))


def konsole_scheme(t: dict) -> str:
    term = t["color"]["terminal"]
    ansi = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
    out = [f"# {HEADER}", "[General]", "Description=Cast Hub", "Opacity=1", "Blur=false", ""]
    out += ["[Background]", f"Color={rgb(term['bg'])}", "", "[BackgroundIntense]", f"Color={rgb(term['bg'])}", ""]
    out += ["[BackgroundFaint]", f"Color={rgb(term['bg'])}", ""]
    out += ["[Foreground]", f"Color={rgb(term['fg'])}", "", "[ForegroundIntense]", "Color=255,255,255", ""]
    out += ["[ForegroundFaint]", f"Color={rgb(term['muted'])}", ""]
    for i, name in enumerate(ansi):
        base = term[name]
        out += [f"[Color{i}]", f"Color={rgb(base)}", ""]
        out += [f"[Color{i}Intense]", f"Color={rgb(mix(base, '#FFFFFF', 0.25))}", ""]
        out += [f"[Color{i}Faint]", f"Color={rgb(mix(base, term['bg'], 0.4))}", ""]
    return "\n".join(out)


def contrast(a: str, b: str) -> float:
    """WCAG contrast ratio between two hex colours."""
    def lum(h: str) -> float:
        def ch(c: int) -> float:
            v = c / 255
            return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
        h = h.lstrip("#")
        r, g, b_ = (int(h[i : i + 2], 16) for i in (0, 2, 4))
        return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b_)
    hi, lo = sorted((lum(a), lum(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def status_text(t: dict, variant: str) -> dict[str, str]:
    """Status colours for use as TEXT: the token colour, nudged toward the theme's text
    colour only as far as needed to read at >= 4.5:1 on the window surface. On dark the
    pastels pass as they are; on light they deepen toward ink."""
    c = t["color"]
    surface, fg = c[variant]["surface"], c[variant]["fg"]
    out = {}
    for k in ("success", "warning", "error", "accent"):
        col, f = c[k], 0.0
        while contrast(col, surface) < 4.5 and f < 1:
            f += 0.05
            col = mix(c[k], fg, f)
        out[k] = col
    return out


def kde_colors(t: dict, variant: str) -> str:
    """A Plasma colour scheme (.colors) for the light or dark theme."""
    c = t["color"]
    v = c[variant]
    inv = c["dark" if variant == "light" else "light"]
    st = status_text(t, variant)
    name = "CastHub" + variant.capitalize()

    def roles(bg: str, alt: str, fg: str, muted: str) -> list[str]:
        return [
            f"BackgroundAlternate={rgb(alt)}", f"BackgroundNormal={rgb(bg)}",
            f"DecorationFocus={rgb(c['accent'])}", f"DecorationHover={rgb(c['accent'])}",
            f"ForegroundActive={rgb(st['accent'])}", f"ForegroundInactive={rgb(muted)}",
            f"ForegroundLink={rgb(st['accent'])}", f"ForegroundNegative={rgb(st['error'])}",
            f"ForegroundNeutral={rgb(st['warning'])}", f"ForegroundNormal={rgb(fg)}",
            f"ForegroundPositive={rgb(st['success'])}", f"ForegroundVisited={rgb(st['accent'])}",
        ]

    sections = {
        "Colors:Window": roles(v["surface"], v["bg"], v["fg"], v["muted"]),
        "Colors:View": roles(v["surface"], v["bg"], v["fg"], v["muted"]),
        "Colors:Button": roles(v["surface"], v["well"], v["fg"], v["muted"]),
        "Colors:Header": roles(v["surface"], v["bg"], v["fg"], v["muted"]),
        "Colors:Header][Inactive": roles(v["surface"], v["bg"], v["muted"], v["muted"]),
        # Selection = ink fill with paper text (design: selected tile / mode row)
        "Colors:Selection": roles(v["fg"], v["fg"], v["bg"], v["line"]),
        "Colors:Tooltip": roles(v["fg"], v["fg"], v["bg"], v["line"]),
        "Colors:Complementary": roles(inv["surface"], inv["bg"], inv["fg"], inv["muted"]),
    }
    out = [f"# {HEADER}", "[General]", f"ColorScheme={name}", f"Name=Cast Hub {variant.capitalize()}", "shadeSortColumn=false", ""]
    out += ["[KDE]", "contrast=4", ""]
    out += ["[ColorEffects:Disabled]", "Color=" + rgb(v["muted"]), "ColorAmount=0", "ColorEffect=0",
            "ContrastAmount=0.55", "ContrastEffect=1", "IntensityAmount=0.1", "IntensityEffect=2", ""]
    out += ["[ColorEffects:Inactive]", "ChangeSelectionColor=false", "Enable=false", ""]
    for sec, lines in sections.items():
        out += [f"[{sec}]", *lines, ""]
    out += [
        "[WM]",
        f"activeBackground={rgb(v['surface'])}", f"activeBlend={rgb(v['fg'])}", f"activeForeground={rgb(v['fg'])}",
        f"inactiveBackground={rgb(v['surface'])}", f"inactiveBlend={rgb(v['muted'])}", f"inactiveForeground={rgb(v['muted'])}",
        "",
    ]
    return "\n".join(out)


def lnf_id(variant: str) -> str:
    return f"org.casthub.{variant}"


def lnf_metadata(t: dict, variant: str) -> str:
    import json
    meta = {
        "KPackageStructure": "Plasma/LookAndFeel",
        "KPlugin": {
            "Authors": [{"Name": "Cast Hub"}],
            "Description": f"Cast Hub, {variant} ({HEADER})",
            "Id": lnf_id(variant),
            "License": "GPLv2+",
            "Name": f"Cast Hub {variant.capitalize()}",
            "Website": "https://github.com/WhyFenceCode/casthub",
        },
        "Keywords": "Desktop;Workspace;Appearance;Look and Feel;",
        "X-Plasma-APIVersion": "2",
    }
    return json.dumps(meta, indent=4) + "\n"


def lnf_defaults(t: dict, variant: str) -> str:
    """What applying the package changes. Panels come from contents/layouts (Cast Hub shell only)."""
    icons = "breeze-dark" if variant == "dark" else "breeze"
    return "\n".join([
        f"# {HEADER}",
        "[kdeglobals][KDE]", "widgetStyle=Breeze", "",
        "[kdeglobals][General]", f"ColorScheme=CastHub{variant.capitalize()}", "",
        "[kdeglobals][Icons]", f"Theme={icons}", "",
        "[plasmarc][Theme]", "name=casthub", "",
        "[Wallpaper]", "Image=CastHub", "",
        "[kcminputrc][Mouse]", "cursorTheme=breeze_cursors", "",
        "[kwinrc][org.kde.kdecoration2]", "library=org.kde.kwin.aurorae", "theme=org.casthub.decoration", "",
        "[ksplashrc][KSplash]", f"Theme={lnf_id(variant)}", "",
    ])


def lnf_splash(t: dict, variant: str) -> str:
    src = (ROOT / "shell" / "ksplash" / "Splash.qml").read_text()
    marker = "readonly property bool dark: false // @variant"
    assert marker in src, "shell/ksplash/Splash.qml lost its @variant line"
    return f"// {HEADER} (from shell/ksplash/Splash.qml)\n" + src.replace(
        marker, f"readonly property bool dark: {str(variant == 'dark').lower()}")


def kwin_script(t: dict) -> str:
    """The KWin views script with the shared desktop geometry filled in from the tokens."""
    src = (ROOT / "shell" / "kwin-script" / "main.js.in").read_text()
    g, sh = t["grid"], t["shell"]
    consts = {
        "FRAME_H": t["frame"]["height"], "MARGIN": g["margin"], "GUTTER": g["gutter"], "COLUMNS": g["columns"],
        "PANEL_TOP": sh["panel_top"], "PANEL_HEADER": sh["panel_header"], "PANEL_BOTTOM": sh["panel_bottom"],
        "PANEL_FIRST_COL": sh["panel_first_col"],
    }
    for k, v in consts.items():
        src = src.replace(f"@{k}@", str(v))
    assert "@" not in src.split("*/", 1)[-1], "unfilled @CONSTANT@ in main.js.in"
    return f"// {HEADER} (from shell/kwin-script/main.js.in)\n" + src


# ---- Plasma desktop theme frames (SPEC D22) ---------------------------------------------
# Plasma draws every pop-up (notifications, volume/brightness, tray pop-ups, KRunner, tooltips)
# from these nine-piece SVGs. Colours are the colour scheme's (recoloured by Plasma at run time):
# window background with a 1 px rule at the scheme's text colour, faint, like a desktop panel.

def _f(v: float) -> str:
    return f"{v:g}"


def _svg(w: float, h: float, body: list[str], note: str) -> str:
    return "\n".join([
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{_f(w)}" height="{_f(h)}" viewBox="0 0 {_f(w)} {_f(h)}">',
        f"  <!-- {HEADER} {note} -->",
        '  <style id="current-color-scheme" type="text/css">.ColorScheme-Background { color:#ececec; } '
        ".ColorScheme-Text { color:#0b0b0b; }</style>",
        *body, "</svg>", ""])


def _rect(id_: str | None, x, y, w, h, cls: str, op: float = 1) -> str:
    ident = f' id="{id_}"' if id_ else ""
    opacity = f' fill-opacity="{_f(op)}"' if op != 1 else ""
    return (f'<rect{ident} x="{_f(x)}" y="{_f(y)}" width="{_f(w)}" height="{_f(h)}" class="{cls}" '
            f'fill="currentColor"{opacity}/>')


def frame_svg(r: int, margin: int, line_op: float, note: str, prefix: str = "") -> str:
    m = 10                                          # stretchable middle
    x1, x2, x3 = r, r + m, 2 * r + m
    bg, ink = "ColorScheme-Background", "ColorScheme-Text"
    body = []
    for name, cx, cy, sx, sy in (("topleft", x1, x1, -1, -1), ("topright", x2, x1, 1, -1),
                                 ("bottomleft", x1, x2, -1, 1), ("bottomright", x2, x2, 1, 1)):
        sw = 0 if sx * sy > 0 else 1
        ring = (f"M {_f(cx)},{_f(cy + sy * r)} A {r} {r} 0 0 {sw} {_f(cx + sx * r)},{_f(cy)} "
                f"L {_f(cx + sx * (r - 1))},{_f(cy)} A {r - 1} {r - 1} 0 0 {1 - sw} {_f(cx)},{_f(cy + sy * (r - 1))} Z")
        disc = (f"M {_f(cx)},{_f(cy + sy * (r - 1))} A {r - 1} {r - 1} 0 0 {sw} {_f(cx + sx * (r - 1))},{_f(cy)} "
                f"L {_f(cx)},{_f(cy)} Z")
        body.append(f'  <g id="{prefix}{name}"><path d="{disc}" class="{bg}" fill="currentColor"/>'
                    f'<path d="{ring}" class="{ink}" fill="currentColor" fill-opacity="{_f(line_op)}"/></g>')
    edges = {
        "top": [(x1, 0, m, 1, ink, line_op), (x1, 1, m, r - 1, bg, 1)],
        "bottom": [(x1, x3 - 1, m, 1, ink, line_op), (x1, x2, m, r - 1, bg, 1)],
        "left": [(0, x1, 1, m, ink, line_op), (1, x1, r - 1, m, bg, 1)],
        "right": [(x3 - 1, x1, 1, m, ink, line_op), (x2, x1, r - 1, m, bg, 1)],
    }
    for name, parts in edges.items():
        body.append(f'  <g id="{prefix}{name}">' + "".join(_rect(None, *p) for p in parts) + "</g>")
    body.append("  " + _rect(f"{prefix}center", x1, x1, m, m, bg))
    if not prefix:
        for side, (x, y, w, h) in {"top": (x1, -20, 4, margin), "bottom": (x1, x3 + 10, 4, margin),
                                   "left": (-20, x1, margin, 4), "right": (x3 + 10, x1, margin, 4)}.items():
            body.append(f'  <rect id="hint-{side}-margin" x="{_f(x)}" y="{_f(y)}" width="{_f(w)}" height="{_f(h)}" fill="none"/>')
    return _svg(x3, x3, body, note)


def popup_svg(t: dict) -> str:
    return frame_svg(t["radius"]["popup"], 12, 0.22, "Pop-up frame: notifications, OSD, tray, KRunner.")


def tooltip_svg(t: dict) -> str:
    return frame_svg(max(4, t["radius"]["popup"] - 4), 8, 0.22, "Tooltips.")


def bar_meter_svg(t: dict) -> str:
    """Progress bars (volume/brightness OSD, notifications): a 2 px rule, ink over a faint
    track, square ends, like the desktop meters (design pages 7-8)."""
    ink = "ColorScheme-Text"
    body = []
    for prefix, op in (("bar-inactive", 0.15), ("bar-active", 1)):
        pieces = {"topleft": (0, 0, 1, 1), "top": (1, 0, 10, 1), "topright": (11, 0, 1, 1),
                  "left": (0, 1, 1, 0.01), "center": (1, 1, 10, 0.01), "right": (11, 1, 1, 0.01),
                  "bottomleft": (0, 1.01, 1, 1), "bottom": (1, 1.01, 10, 1), "bottomright": (11, 1.01, 1, 1)}
        y0 = 0 if prefix == "bar-inactive" else 4
        for name, (x, y, w, h) in pieces.items():
            body.append("  " + _rect(f"{prefix}-{name}", x, y + y0, w, h, ink, op))
    body.append('  <rect id="hint-bar-size" x="20" y="0" width="4" height="2" fill="none"/>')
    return _svg(24, 8, body, "Progress bar.")


def lnf_layout(t: dict) -> str:
    return f"// {HEADER} (from shell/layout.js)\n" + (ROOT / "shell" / "layout.js").read_text()


OUTPUTS = {
    "uikit/Tokens.qml": qml_tokens,
    "modes/console/CastHub.colorscheme": konsole_scheme,
    "shell/colors/CastHubLight.colors": lambda t: kde_colors(t, "light"),
    "shell/colors/CastHubDark.colors": lambda t: kde_colors(t, "dark"),
}
for _v in ("light", "dark"):
    _d = f"shell/lookandfeel/{lnf_id(_v)}"
    OUTPUTS[f"{_d}/metadata.json"] = lambda t, v=_v: lnf_metadata(t, v)
    OUTPUTS[f"{_d}/contents/defaults"] = lambda t, v=_v: lnf_defaults(t, v)
    OUTPUTS[f"{_d}/contents/splash/Splash.qml"] = lambda t, v=_v: lnf_splash(t, v)
    OUTPUTS[f"{_d}/contents/layouts/org.casthub.desktop-layout.js"] = lnf_layout
OUTPUTS["shell/kwin-script/org.casthub.views/contents/code/main.js"] = kwin_script
OUTPUTS["shell/plasma-theme/casthub/dialogs/background.svg"] = popup_svg
OUTPUTS["shell/plasma-theme/casthub/widgets/tooltip.svg"] = tooltip_svg
OUTPUTS["shell/plasma-theme/casthub/widgets/bar_meter_horizontal.svg"] = bar_meter_svg
# The shell's own first-run layout, used when the user's global theme has none for this shell.
OUTPUTS["shell/plasma-shell/org.casthub.desktop/contents/layout.js"] = lnf_layout


def main() -> int:
    tokens = load()
    check = "--check" in sys.argv
    stale = []
    for rel, fn in OUTPUTS.items():
        path = ROOT / rel
        content = fn(tokens)
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {rel}")
    if stale:
        print("stale generated files (run brand/build.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
