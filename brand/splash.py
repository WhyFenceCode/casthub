#!/usr/bin/env python3
"""Build the Cast Hub Plymouth theme (boot splash): always dark, signature writes itself.

Run at install time (as the normal user; tools/install-splash.sh installs the output):

    python3 brand/splash.py --out local/splash-build --width 1920 --height 1080 --host <name>

Layout from design page 2. Text is pre-rendered to PNGs so the initramfs needs no
fonts. The script is generated with every file name written out literally, so the
Plymouth script never has to turn numbers into strings.
"""

from __future__ import annotations

import argparse
import shutil
import sys
import tomllib
from pathlib import Path

import cairo
import gi

gi.require_version("Pango", "1.0")
gi.require_version("PangoCairo", "1.0")
from gi.repository import Pango, PangoCairo  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import signature  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
REFRESH_HZ = 50            # Plymouth calls the refresh function ~50 times a second

STATUS = {                 # Plymouth.GetMode() → status line
    "boot": "Starting services",
    "shutdown": "Shutting down",
    "reboot": "Restarting",
    "updates": "Installing updates",
    "system-upgrade": "Upgrading system",
    "firmware-upgrade": "Updating firmware",
}
ESC_HINT = "Esc – show boot log"


def tokens() -> dict:
    return tomllib.loads((ROOT / "brand" / "tokens.toml").read_text())


def hex_rgb(h: str) -> tuple[float, float, float]:
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))  # type: ignore[return-value]


def render_label(path: Path, text: str, px: float, tracking_em: float, fg: str, bg: str, square: str | None = None) -> tuple[int, int]:
    """Uppercase mono label, opaque on the splash background. Returns (w, h)."""
    font = Pango.FontDescription.from_string("DM Mono")
    font.set_absolute_size(px * Pango.SCALE)
    probe = cairo.Context(cairo.ImageSurface(cairo.FORMAT_RGB24, 1, 1))
    layout = PangoCairo.create_layout(probe)
    layout.set_font_description(font)
    attrs = Pango.AttrList()
    attrs.insert(Pango.attr_letter_spacing_new(int(tracking_em * px * Pango.SCALE)))
    layout.set_attributes(attrs)
    layout.set_text(text.upper(), -1)
    _, log = layout.get_pixel_extents()
    sq = round(px * 0.65) if square else 0
    gap = round(px * 0.8) if square else 0
    w, h = sq + gap + log.width + 2, log.height + 2
    surf = cairo.ImageSurface(cairo.FORMAT_RGB24, w, h)
    ctx = cairo.Context(surf)
    ctx.set_source_rgb(*hex_rgb(bg))
    ctx.paint()
    if square:
        ctx.set_source_rgb(*hex_rgb(square))
        ctx.rectangle(0, (h - sq) / 2, sq, sq)
        ctx.fill()
    ctx.move_to(sq + gap, 1)
    ctx.set_source_rgb(*hex_rgb(fg))
    PangoCairo.update_layout(ctx, layout)
    PangoCairo.show_layout(ctx, layout)
    surf.write_to_png(str(path))
    return w, h


def build(out: Path, width: int, height: int, host: str, fps: int) -> None:
    t = tokens()
    dark, accent = dict(t["color"]["dark"]), t["color"]["accent"]
    dark["bg"] = t["boot"]["bg"]                 # pure black behind everything on the splash
    label = t["type"]["label"]
    u = height / t["frame"]["height"]
    margin = t["grid"]["margin"] * u
    px = label["size"] * u

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    meta = signature.write_frames(out, height, width, fps)

    # Labels (design page 2): host top-left, status bottom-left, Esc hint centred at the bottom.
    hw, hh = render_label(out / "label-host.png", host, px, label["tracking"], dark["fg"], dark["bg"]) if host else (0, 0)
    status_sizes = {}
    for mode, text in STATUS.items():
        status_sizes[mode] = render_label(out / f"status-{mode}.png", text, px, label["tracking"], dark["fg"], dark["bg"], square=accent)
    ew, eh = render_label(out / "label-esc.png", ESC_HINT, px, label["tracking"], dark["muted"], dark["bg"])

    top_y = round(23.5 * u)                      # centre line of the top label
    bottom_y = round(height - 36 * u)            # centre line of the bottom labels (as on the login screen)
    r, g, b = hex_rgb(dark["bg"])
    ticks = REFRESH_HZ / fps

    last = meta["frames"] - 1
    sh = status_sizes["boot"][1]
    lines = [
        "# Cast Hub boot splash. GENERATED by brand/splash.py at install time. Do not edit.",
        f"# Laid out for a {width}x{height} reference screen, then re-centred and scaled to the",
        "# smallest attached screen every time the screens change (the firmware framebuffer is",
        "# replaced by the real driver during boot; a second monitor can appear), so the signature",
        "# is never shown off-centre or cut off.",
        f"Window.SetBackgroundTopColor({r:.4f}, {g:.4f}, {b:.4f});",
        f"Window.SetBackgroundBottomColor({r:.4f}, {g:.4f}, {b:.4f});",
        "",
    ]
    for i in range(meta["frames"]):
        lines.append(f'files[{i}] = "sig-{i}.png";')
    lines += [
        "",
        "global.scale = 1;",
        "global.seen_w = -1;",
        "global.seen_h = -1;",
        "global.shown = 0;",
        "global.tick = 0;",
        "",
        "fun sig_image(frame) {",
        "    img = Image(global.files[frame]);",
        "    if (global.scale != 1)",
        "        img = img.Scale(Math.Int(img.GetWidth() * global.scale), Math.Int(img.GetHeight() * global.scale));",
        "    return img;",
        "}",
        "",
        "sig = Sprite();",
        "sig.SetZ(1);",
    ]
    if host:
        lines += ['host = Sprite(Image("label-host.png"));', "host.SetZ(2);"]
    lines += ['mode = Plymouth.GetMode();', 'status_file = "status-boot.png";']
    for mode in STATUS:
        if mode != "boot":
            lines.append(f'if (mode == "{mode}") status_file = "status-{mode}.png";')
    lines += [
        "status = Sprite(Image(status_file));",
        "status.SetZ(2);",
        'esc = Sprite(Image("label-esc.png"));',
        "esc.SetZ(2);",
        "",
        "fun layout() {",
        "    w = Window.GetWidth(0);",
        "    h = Window.GetHeight(0);",
        "    for (i = 1; i < 8; i++) {",
        "        if (Window.GetWidth(i) && Window.GetWidth(i) < w) w = Window.GetWidth(i);",
        "        if (Window.GetHeight(i) && Window.GetHeight(i) < h) h = Window.GetHeight(i);",
        "    }",
        "    global.seen_w = Window.GetWidth(0);",
        "    global.seen_h = Window.GetHeight(0);",
        "    cx = Window.GetX(0) + Window.GetWidth(0) / 2;",
        "    cy = Window.GetY(0) + Window.GetHeight(0) / 2;",
        f"    global.scale = h / {height};",
        f"    if (w / {width} < global.scale) global.scale = w / {width};",
        "    if (global.scale > 0.97 && global.scale < 1.03) global.scale = 1;",
        "    left = cx - w / 2;",
        "    top = cy - h / 2;",
        "    s = global.scale;",
        f"    global.sig.SetPosition(Math.Int(cx + ({meta['x']} - {width / 2:g}) * s),"
        f" Math.Int(cy + ({meta['y']} - {height / 2:g}) * s), 1);",
        "    global.sig.SetImage(sig_image(global.shown));",
    ]
    if host:
        lines.append(f"    global.host.SetPosition(Math.Int(left + {round(margin)} * s), Math.Int(top + {top_y} * s - {hh // 2}), 2);")
    lines += [
        f"    global.status.SetPosition(Math.Int(left + {round(margin)} * s), Math.Int(top + h - {height - bottom_y} * s - {sh // 2}), 2);",
        f"    global.esc.SetPosition(Math.Int(cx - {ew // 2}), Math.Int(top + h - {height - bottom_y} * s - {eh // 2}), 2);",
        "}",
        "layout();",
        "",
        "# Write the signature once, then hold the last frame. Re-lay out if the screens change.",
        "fun refresh_callback() {",
        "    if (Window.GetWidth(0) != global.seen_w || Window.GetHeight(0) != global.seen_h) layout();",
        "    global.tick = global.tick + 1;",
        f"    frame = Math.Int(global.tick / {ticks:g});",
        f"    if (frame > {last}) frame = {last};",
        "    if (frame != global.shown) {",
        "        global.shown = frame;",
        "        global.sig.SetImage(sig_image(frame));",
        "    }",
        "}",
        "Plymouth.SetRefreshFunction(refresh_callback);",
        "",
        "# Plymouth hands the screen over (to the login screen, or at shutdown) with whatever was",
        "# drawn last still showing: always leave the whole signature, never a half-written one.",
        "fun quit_callback() {",
        f"    global.shown = {last};",
        f"    global.tick = {meta['frames'] * ticks:g};",
        "    layout();",
        "}",
        "Plymouth.SetQuitFunction(quit_callback);",
        "",
    ]
    (out / "casthub.script").write_text("\n".join(lines))
    (out / "casthub.plymouth").write_text(
        "[Plymouth Theme]\n"
        "Name=Cast Hub\n"
        "Description=Torsten Young signature, written on boot\n"
        "ModuleName=script\n\n"
        "[script]\n"
        "ImageDir=/usr/share/plymouth/themes/casthub\n"
        "ScriptFile=/usr/share/plymouth/themes/casthub/casthub.script\n"
    )
    print(f"built {out}: {meta['frames']} frames at {fps} fps, signature {meta['w']}x{meta['h']} at ({meta['x']},{meta['y']})")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--width", type=int, default=1920)
    ap.add_argument("--height", type=int, default=1080)
    ap.add_argument("--host", default="", help="machine name shown top-left (empty: none)")
    ap.add_argument("--fps", type=int, default=25)
    a = ap.parse_args()
    build(a.out, a.width, a.height, a.host, a.fps)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
